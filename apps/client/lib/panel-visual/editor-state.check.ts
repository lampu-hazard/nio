import assert from 'node:assert/strict';
import { createEditorHistory, editorReducer, toScenePoint, createCanvasFromSimple, snapCoordinate } from './editor-state';
import type { CanvasScene } from './generated/panel-visual.document';

const scene: CanvasScene = { width: 600, height: 400, background: '#141719', description: 'Banner', elements: [{ id: 'a', type: 'rectangle', x: 10, y: 20, width: 100, height: 80, fill: '#ffffff', radius: 0 }] };
assert.deepEqual(toScenePoint({ x: 150, y: 100 }, { left: 50, top: 50 }, 0.5), { x: 200, y: 100 });
let history = createEditorHistory(scene);
history = editorReducer(history, { type: 'begin' });
for (let x = 11; x < 100; x++) history = editorReducer(history, { type: 'patch', id: 'a', patch: { x } });
history = editorReducer(history, { type: 'commit' });
assert.equal(history.past.length, 1);
assert.equal((history.present.elements[0] as any).x, 99);
const moved = history.present;
history = editorReducer(history, { type: 'undo' });
assert.deepEqual(history.present, scene);
history = editorReducer(history, { type: 'redo' });
assert.deepEqual(history.present, moved);
for (let x = 100; x < 151; x++) history = editorReducer(history, { type: 'patch', id: 'a', patch: { x } });
assert.equal(history.past.length, 50);
history = editorReducer(history, { type: 'duplicate', id: 'a', newId: 'b' });
assert.deepEqual(history.present.elements.map(e => e.id), ['a', 'b']);
history = editorReducer(history, { type: 'resize-artboard', width: 1000, height: 1000 });
assert.equal((history.present.elements[0] as any).x, 150);
history = editorReducer(history, { type: 'reorder', ids: ['b', 'a'] });
assert.deepEqual(history.present.elements.map(e => e.id), ['b', 'a']);
history = editorReducer(history, { type: 'delete', id: 'b' });
assert.equal(history.present.elements.length, 1);
assert.equal(snapCoordinate(102, [100, 104], 3), 100);
const original = { title: 'Welcome', description: 'Read rules', accentText: 'Server', imageUrl: 'https://cdn.example/banner.png' };
const converted = createCanvasFromSimple(original);
assert.equal(original.description, 'Read rules');
assert.equal(converted.editorMode, 'CANVAS');
assert.ok(converted.canvas?.elements.some(e => e.type === 'text' && e.text.includes('Read rules')));
assert.deepEqual(converted.native?.blocks, []);
console.log('Panel editor state checks passed');
