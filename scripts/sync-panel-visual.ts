import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dir, '..');
const source = resolve(root, 'apps/server/src/panels/visual');
const target = resolve(root, 'apps/client/lib/panel-visual/generated');
const modules = ['panel-visual.document.ts', 'panel-media-url.ts'];
const check = process.argv.includes('--check');
let mismatch = false;
for (const name of modules) {
  const content = '// Generated by scripts/sync-panel-visual.ts; edit the server source instead.\n' + (await readFile(resolve(source, name), 'utf8')).replace(/\r\n/g, '\n');
  const current = await readFile(resolve(target, name), 'utf8').catch(() => '');
  if (current.replace(/\r\n/g, '\n') === content) continue;
  if (check) {
    console.error(`Panel visual contract out of sync: ${name}`);
    mismatch = true;
  } else {
    await mkdir(target, { recursive: true });
    await writeFile(resolve(target, name), content);
  }
}
if (mismatch) process.exitCode = 1;
